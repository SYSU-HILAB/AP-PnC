"""
Dataset module for aerodynamics ML training.

Handles CSV loading, parquet assembly, train/val splitting.
"""

from dataclasses import dataclass
from pathlib import Path

import numpy as np
import pandas as pd

from tooling.env import artifact_path, project_path

# Map CSV filename to aero_type identifier
AERO_TYPE_MAP: dict[str, str] = {
    "lyu_across_AoAs.csv": "lyu",
    "bspline_across_AoAs.csv": "bspline",
    "phi_across_AoAs.csv": "phi",
    "advanced_across_AoAs.csv": "advanced",
}


@dataclass
class AeroMLDataset:
    """Dataset for aerodynamics ML training."""

    df: pd.DataFrame

    @classmethod
    def from_csv_files(
        cls,
        csv_dir: str | Path,
        aero_types: list[str] | None = None,
    ) -> "AeroMLDataset":
        """
        Load and merge CSV files into single dataset.

        NOTE: CSV files are used as data source to avoid pybind11 binding issues.
        The 'advanced' CSV data was generated by C++ code and is valid for training.

        Args:
            csv_dir: Directory containing CSV files
            aero_types: List of aero types to load (default: all 4 types)

        Returns:
            AeroMLDataset with combined data
        """
        csv_dir = project_path(csv_dir)
        if aero_types is None:
            aero_types = ["lyu", "bspline", "phi", "advanced"]

        dfs = []
        for csv_file, aero_type in AERO_TYPE_MAP.items():
            if aero_type not in aero_types:
                continue

            csv_path = csv_dir / csv_file
            if not csv_path.exists():
                raise FileNotFoundError(f"CSV file not found: {csv_path}")

            # Read CSV: alpha(rad),cx,cz
            df = pd.read_csv(csv_path)

            # Handle NaN values (e.g., from C++ bug at alpha=0)
            # Use linear interpolation to fill NaN values
            if df.isna().any().any():
                nan_count = df.isna().sum().sum()
                print(f"Warning: Found {nan_count} NaN values in {csv_file}, interpolating...")
                # Interpolate NaN values
                df = df.interpolate(method="linear", limit_direction="both")
                # Fill any remaining NaN (at edges) with forward/backward fill
                df = df.ffill().bfill()

            # Rename columns to match schema
            df = df.rename(columns={"alpha(rad)": "alpha"})

            # Add aero_type column
            df["aero_type"] = aero_type

            # Compute input features
            df["cos_alpha"] = np.cos(df["alpha"].values)
            df["sin_alpha"] = np.sin(df["alpha"].values)

            # Add weight_path column (empty initially)
            df["weight_path"] = None

            dfs.append(df)

        combined_df = pd.concat(dfs, ignore_index=True)
        return cls(df=combined_df)

    def filter_by_type(self, aero_type: str) -> "AeroMLDataset":
        """Return dataset for single aerodynamics type."""
        if aero_type not in self.df["aero_type"].values:
            raise ValueError(f"Aero type '{aero_type}' not found in dataset")

        filtered_df = self.df[self.df["aero_type"] == aero_type].copy()
        return AeroMLDataset(df=filtered_df)

    def split_train_val(
        self,
        train_ratio: float = 0.8,
        seed: int = 42,
    ) -> tuple["AeroMLDataset", "AeroMLDataset"]:
        """Split into training and validation sets."""
        rng = np.random.default_rng(seed)

        # Shuffle indices
        indices = rng.permutation(len(self.df))
        split_idx = int(len(indices) * train_ratio)

        train_indices = indices[:split_idx]
        val_indices = indices[split_idx:]

        train_df = self.df.iloc[train_indices].reset_index(drop=True)
        val_df = self.df.iloc[val_indices].reset_index(drop=True)

        return AeroMLDataset(df=train_df), AeroMLDataset(df=val_df)

    def to_parquet(self, path: str | Path) -> None:
        """Save dataset to parquet file."""
        path = artifact_path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        self.df.to_parquet(path, index=False)

    @classmethod
    def from_parquet(cls, path: str | Path) -> "AeroMLDataset":
        """Load dataset from parquet file."""
        df = pd.read_parquet(project_path(path))
        return cls(df=df)

    def update_weight_path(self, aero_type: str, weight_path: str | Path) -> None:
        """Update weight_path for a specific aerodynamics type."""
        weight_path_str = str(project_path(weight_path))
        self.df.loc[self.df["aero_type"] == aero_type, "weight_path"] = weight_path_str

    def get_features(self) -> np.ndarray:
        """Get input features (cos_alpha, sin_alpha)."""
        return self.df[["cos_alpha", "sin_alpha"]].values.astype(np.float32)

    def get_targets(self) -> np.ndarray:
        """Get output targets (cx, cz)."""
        return self.df[["cx", "cz"]].values.astype(np.float32)

    def __len__(self) -> int:
        return len(self.df)

    def __repr__(self) -> str:
        aero_counts = self.df["aero_type"].value_counts().to_dict()
        return f"AeroMLDataset(n={len(self)}, aero_types={aero_counts})"


def assemble_parquet_dataset(
    csv_dir: str | Path = ".artifacts/aerodynamics",
    output_path: str | Path = ".artifacts/aerodynamics/aero_ml_dataset.parquet",
    aero_types: list[str] | None = None,
) -> AeroMLDataset:
    """
    Assemble parquet dataset from CSV files.

    Args:
        csv_dir: Directory containing CSV files
        output_path: Output parquet file path
        aero_types: List of aero types to load (default: lyu, bspline, phi)

    Returns:
        AeroMLDataset
    """
    dataset = AeroMLDataset.from_csv_files(csv_dir, aero_types=aero_types)
    dataset.to_parquet(output_path)

    print(f"Dataset assembled: {dataset}")
    print(f"Saved to: {output_path}")

    return dataset
