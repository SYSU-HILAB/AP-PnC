import os
from collections.abc import Sequence
from pathlib import Path

import numpy as np
from scipy.interpolate import interp1d

from feature.utils import Colors, color_print


TEMP_DATA_SUBDIR = Path("artifacts") / "simulations" / "temp_data"


def _repo_root() -> Path:
    """Best-effort repository root detection."""
    return Path(os.environ.get("AP_PNC_DIR", Path(__file__).resolve().parents[3]))


def _temp_data_dir() -> Path:
    return _repo_root() / TEMP_DATA_SUBDIR


def _find_planning_csv() -> Path | None:
    """Locate the latest planning CSV emitted by the global planner."""
    temp_dir = _temp_data_dir()
    if not temp_dir.exists():
        return None

    planning_files = sorted(
        (path for path in temp_dir.glob("planning_*.csv") if path.is_file()),
        key=lambda p: p.stat().st_mtime,
        reverse=True,
    )
    if planning_files:
        return planning_files[0]

    fallback = temp_dir / "planning.csv"
    if fallback.is_file():
        return fallback
    return None


def _stack_columns(data: np.ndarray, columns: Sequence[str]) -> np.ndarray:
    """Stack named columns into a matrix."""
    names = data.dtype.names or []
    missing = [name for name in columns if name not in names]
    if missing:
        raise ValueError(f"Missing required columns in trajectory CSV: {missing}")
    stacked = np.column_stack([np.atleast_1d(data[name]) for name in columns])
    return stacked


def load_trajectory_csv(csv_path: str) -> dict[str, np.ndarray]:
    """
    Load trajectory data from a planner-generated CSV.

    Required columns (emitted by global_planning.cpp):
    time,pos_x,pos_y,pos_z,vel_x,vel_y,vel_z,yb_x,yb_y,yb_z,quat_w,quat_x,quat_y,quat_z

    Optional columns: thrust,df_alpha,real_alpha,aero_force_z,ap_x,ap_y,ap_z,
    S_ap_x,S_ap_z,B_Omega_b_y,alpha_dot,B_aero_force_z

    NOTE: quaternion columns (quat_w,quat_x,quat_y,quat_z) are REQUIRED.
    Older v14-alpha.csv files without orientation data are NOT supported.
    """
    csv_path_obj = Path(csv_path)
    if not csv_path_obj.exists():
        raise FileNotFoundError(f"Trajectory CSV not found: {csv_path}")

    data = np.genfromtxt(csv_path_obj, delimiter=",", names=True)
    if data.ndim == 0:
        data = np.array([data], dtype=data.dtype)

    names = data.dtype.names or []

    # ========================================================================
    # Field Validation with Pretty Printing
    # ========================================================================

    color_print("Trajectory CSV Validation", Colors.BOLD + Colors.BLUE)
    color_print(f"  File: {csv_path_obj}", Colors.BLUE)

    # Required fields
    required_fields = {
        "time": "Time vector",
        "pos_x, pos_y, pos_z": "Position (3D)",
        "vel_x, vel_y, vel_z": "Velocity (3D)",
        "yb_x, yb_y, yb_z": "Body Y-axis",
        "quat_w, quat_x, quat_y, quat_z": "Quaternion (WXYZ)",
    }

    missing_required = []
    for field_key, desc in required_fields.items():
        field_names = [f.strip() for f in field_key.split(",")]
        if all(f in names for f in field_names):
            color_print(f"  {Colors.CHECKMARK} {desc:20} ({field_key})", Colors.GREEN)
        else:
            missing_fields = [f for f in field_names if f not in names]
            color_print(
                f"  {Colors.CROSS} {desc:20} ({field_key}) "
                f"[{Colors.BOLD}MISSING: {missing_fields}{Colors.BOLD + Colors.RED}]",
                Colors.RED,
            )
            missing_required.extend(missing_fields)

    if missing_required:
        color_print(
            f"\n{Colors.BOLD}ERROR:{Colors.RED + Colors.BOLD} Not a valid trajectory CSV!",
            Colors.RED + Colors.BOLD,
        )
        color_print(f"  Missing required fields: {missing_required}", Colors.BOLD + Colors.RED)
        color_print(
            "  Please use a CSV generated by global_planning.cpp with full orientation data.",
            Colors.YELLOW,
        )
        raise ValueError(f"Missing required columns: {missing_required}")

    # Optional fields
    optional_fields = {
        "thrust": "Thrust command",
        "df_alpha": "DF Alpha (differential flatness)",
        "real_alpha": "Real Alpha",
        "real_quat_w, real_quat_x, real_quat_y, real_quat_z": "Real Quaternion",
        "aero_force_z": "Aerodynamic force Z",
        "ap_x, ap_y, ap_z": "Aerodynamic center",
        "S_ap_x, S_ap_z": "Aerodynamic derivatives",
        "B_Omega_b_y": "Body angular rate Y",
        "alpha_dot": "Alpha rate of change",
        "B_aero_force_z": "Aerodynamic force Z (body)",
    }

    color_print("\nOptional Fields:", Colors.YELLOW)
    for field_key, desc in optional_fields.items():
        field_names = [f.strip() for f in field_key.split(",")]
        if all(f in names for f in field_names):
            color_print(f"  {Colors.CHECKMARK} {desc:30} ({field_key})", Colors.GREEN)
        else:
            color_print(f"  {Colors.CROSS} {desc:30} ({field_key})", Colors.RESET)

    # ========================================================================
    # Load Data
    # ========================================================================

    trajectory: dict[str, np.ndarray] = {}
    trajectory["time"] = np.atleast_1d(data["time"])
    trajectory["position"] = _stack_columns(data, ["pos_x", "pos_y", "pos_z"])
    trajectory["velocity"] = _stack_columns(data, ["vel_x", "vel_y", "vel_z"])
    trajectory["yb"] = _stack_columns(data, ["yb_x", "yb_y", "yb_z"])

    thrust_col = "thrust" if "thrust" in names else None
    trajectory["thrust"] = (
        np.atleast_1d(data[thrust_col]) if thrust_col else np.zeros_like(trajectory["time"])
    )

    alpha_col = None
    if "df_alpha" in names:
        alpha_col = "df_alpha"
    elif "alpha" in names:
        alpha_col = "alpha"
    trajectory["alpha"] = (
        np.atleast_1d(data[alpha_col]) if alpha_col else np.zeros_like(trajectory["time"])
    )

    quat_columns = ["quat_w", "quat_x", "quat_y", "quat_z"]
    trajectory["quaternion"] = _stack_columns(data, quat_columns)

    # Load real_alpha if available
    real_alpha_col = None
    if "real_alpha" in names:
        real_alpha_col = "real_alpha"
        trajectory["real_alpha"] = np.atleast_1d(data[real_alpha_col])
    else:
        trajectory["real_alpha"] = None

    # Load or compute real_quat
    real_quat_columns = ["real_quat_w", "real_quat_x", "real_quat_y", "real_quat_z"]
    if all(q in names for q in real_quat_columns):
        # Load from CSV if available
        trajectory["real_quat"] = _stack_columns(data, real_quat_columns)
    elif trajectory["real_alpha"] is not None:
        # Compute from real_alpha and velocity using alpha_to_quat
        from feature.utils.math_utils import alpha_to_quat

        real_quats = []
        for i in range(len(trajectory["time"])):
            alpha = trajectory["real_alpha"][i]
            vel = trajectory["velocity"][i]
            q = alpha_to_quat(alpha, vel)
            real_quats.append(q)
        trajectory["real_quat"] = np.stack(real_quats, axis=0)
    else:
        trajectory["real_quat"] = None

    # ========================================================================
    # Summary
    # ========================================================================

    color_print(
        f"\n{Colors.CHECKMARK} Successfully loaded trajectory!", Colors.GREEN + Colors.BOLD
    )
    color_print(f"  Points:    {len(trajectory['time'])}", Colors.BLUE)
    color_print(
        f"  Time range: {trajectory['time'][0]:.2f}s → {trajectory['time'][-1]:.2f}s", Colors.BLUE
    )
    color_print(
        f"  Duration:  {trajectory['time'][-1] - trajectory['time'][0]:.2f}s", Colors.BLUE
    )
    print()

    return trajectory


class TrajectoryReference:
    """
    Trajectory reference provider with interpolation.
    Provides reference states for the nMPC controller.
    """

    def __init__(self, trajectory_data: dict[str, np.ndarray]):
        """
        Initialize trajectory reference.

        Args:
            trajectory_data: Dictionary from load_trajectory_csv()
        """
        self.time = trajectory_data["time"]
        self.position = trajectory_data["position"]
        self.velocity = trajectory_data["velocity"]
        self.yb = trajectory_data["yb"]
        self.thrust = trajectory_data.get("thrust", np.zeros(len(self.time)))
        self.alpha = trajectory_data.get("alpha", np.zeros(len(self.time)))
        self.quaternion = trajectory_data.get("quaternion")
        self.real_quat = trajectory_data.get("real_quat")

        # Create interpolators
        self._pos_interp = [
            interp1d(self.time, self.position[:, i], kind="linear", fill_value="extrapolate")
            for i in range(3)
        ]
        self._vel_interp = [
            interp1d(self.time, self.velocity[:, i], kind="linear", fill_value="extrapolate")
            for i in range(3)
        ]
        self._yb_interp = [
            interp1d(self.time, self.yb[:, i], kind="linear", fill_value="extrapolate")
            for i in range(3)
        ]
        self._alpha_interp = interp1d(
            self.time, self.alpha, kind="linear", fill_value="extrapolate"
        )
        self._quat_interp = None
        if self.quaternion is not None:
            self._quat_interp = [
                interp1d(self.time, self.quaternion[:, i], kind="linear", fill_value="extrapolate")
                for i in range(4)
            ]
        self._real_quat_interp = None
        if self.real_quat is not None:
            self._real_quat_interp = [
                interp1d(self.time, self.real_quat[:, i], kind="linear", fill_value="extrapolate")
                for i in range(4)
            ]

    def get_reference_at_time(self, t: float) -> dict[str, np.ndarray]:
        """
        Get interpolated reference state at time t.

        Args:
            t: Time in seconds

        Returns:
            Dictionary with reference state:
            - position: (3,) array
            - velocity: (3,) array
            - yb: (3,) array
            - alpha: scalar
            - quaternion: (4,) array [w, x, y, z] if available
            - real_quat: (4,) array [w, x, y, z] if available
        """
        ref = {
            "position": np.array([f(t) for f in self._pos_interp]),
            "velocity": np.array([f(t) for f in self._vel_interp]),
            "yb": np.array([f(t) for f in self._yb_interp]),
            "alpha": float(self._alpha_interp(t)),
        }
        if self._quat_interp:
            quat = np.array([f(t) for f in self._quat_interp])
            norm = np.linalg.norm(quat)
            if norm > 1e-6:
                quat = quat / norm
            ref["quaternion"] = quat
        if self._real_quat_interp:
            real_quat = np.array([f(t) for f in self._real_quat_interp])
            norm = np.linalg.norm(real_quat)
            if norm > 1e-6:
                real_quat = real_quat / norm
            ref["real_quat"] = real_quat
        return ref

    def get_reference_window(self, t: float, horizon: float, dt: float) -> dict[str, np.ndarray]:
        """
        Get reference trajectory for MPC prediction horizon.

        Args:
            t: Current time
            horizon: Prediction horizon length (seconds)
            dt: Time step within horizon

        Returns:
            Dictionary with reference arrays:
            - position: (N, 3) array
            - velocity: (N, 3) array
            - yb: (N, 3) array
        """
        N = int(horizon / dt)
        times = t + np.arange(N + 1) * dt

        position_ref = np.array([[f(tau) for f in self._pos_interp] for tau in times])
        velocity_ref = np.array([[f(tau) for f in self._vel_interp] for tau in times])
        yb_ref = np.array([[f(tau) for f in self._yb_interp] for tau in times])

        ref = {
            "position": position_ref,
            "velocity": velocity_ref,
            "yb": yb_ref,
        }
        if self._quat_interp:
            quat_ref = []
            for tau in times:
                quat = np.array([f(tau) for f in self._quat_interp])
                norm = np.linalg.norm(quat)
                if norm > 1e-6:
                    quat = quat / norm
                quat_ref.append(quat)
            ref["quaternion"] = np.vstack(quat_ref)

        return ref


def get_trajectory_path() -> str:
    """
    Get the default trajectory file path (v14-alpha.csv).

    Returns:
        Path to the latest planner output (fallback to v14-alpha.csv)
    """
    planning_csv = _find_planning_csv()
    if planning_csv:
        return str(planning_csv)
    return str(Path(__file__).parent / "refs" / "v14-alpha.csv")
